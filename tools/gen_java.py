def main():
    guide_java()
    worldblocks_java()
    metals_java()
    machines_java()
    furniture_java()
    skills_java()
    decor_java()
    boss_gear_java()
    from wf import npcs
    npc_out = os.path.join(os.path.dirname(OUT), "GeneratedNpcs.java")
    with open(npc_out, "w") as f:
        f.write(npcs.java())
    print(f"wrote {os.path.relpath(npc_out, ROOT)}")
    chapters = json.load(open(QUESTS))
    lines = [
        "package com.wayfarers.generated;",
        "",
        "import java.util.List;",
        "",
        "/** GENERATED by tools/gen_java.py — do not edit by hand. */",
        "public final class GeneratedContent {",
        "    public record StructureInfo(String id, String dimension) {}",
        "",
        "    public record Chapter(String id, List<String> quests) {}",
        "",
        "    public static final List<StructureInfo> STRUCTURES = List.of(",
    ]
    entries = [f'            new StructureInfo("{s.id}", "{s.dimension}")' for s in defs.STRUCTURES]
    lines.append(",\n".join(entries))
    lines += ["    );", "", "    public static final List<Chapter> CHAPTERS = List.of("]
    ch = []
    for cid, quests in chapters.items():
        qs = ", ".join(f'"{q}"' for q in quests)
        ch.append(f'            new Chapter("{cid}", List.of({qs}))')
    lines.append(",\n".join(ch))
    lines += ["    );", ""]
    info_path = os.path.join(ROOT, "build", "quest_info.json")
    info = json.load(open(info_path)) if os.path.exists(info_path) else {}
    lines.append("    /** Quest rewards shown in the journal: \"xp|item*count;item*count\". */")
    lines.append("    public static final java.util.Map<String, String> REWARDS = java.util.Map.ofEntries(")
    ents = []
    for q, v in sorted(info.items()):
        items = ";".join(f"{i}*{c}" for i, c in v["items"])
        ents.append(f'            java.util.Map.entry("{q}", "{v["xp"]}|{items}")')
    lines.append(",\n".join(ents))
    lines += ["    );", "", "    private GeneratedContent() {}", "}", ""]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
